// Node-native cases use a separate filename pattern from the root Vitest suite.
const { test } = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs/promises')
const os = require('node:os')
const path = require('node:path')
const { assetPath, serveAsset } = require('../src/assets.cjs')
const { localUrl, arduinoUrl, externalUrl } = require('../src/policy.cjs')

test('protocol confines files, supports SPA routes and rejects malformed/traversal requests', () => {
  const root = path.join(os.tmpdir(), 'rtp-assets')
  assert.equal(assetPath(root, 'rtp://app/map?intro=1'), path.join(root, 'index.html'))
  assert.equal(assetPath(root, 'rtp://app/assets/main.js'), path.join(root, 'assets', 'main.js'))
  for (const bad of ['file:///etc/passwd', 'rtp://evil/index.html', 'rtp://app/%2e%2e%2fsecret', 'rtp://app/%5csecret', 'rtp://app/%00', 'rtp://app/C:/secret', 'rtp://app/%zz']) {
    assert.equal(assetPath(root, bad), null, bad)
  }
  assert.equal(localUrl('rtp://app.attacker/'), null)
  assert.equal(localUrl('rtp://someone@app/'), null)
  assert.equal(arduinoUrl('rtp://app/arduino.html'), true)
  assert.equal(arduinoUrl('rtp://app/map'), false)
})

test('external opening permits known HTTPS links only, never OS protocols or deceptive hosts', () => {
  assert.equal(externalUrl('https://drive.google.com/drive/folders/test'), 'https://drive.google.com/drive/folders/test')
  assert.equal(externalUrl('https://github.com/franshessss2/red-tide-ppc'), 'https://github.com/franshessss2/red-tide-ppc')
  for (const bad of ['file:///C:/Windows/system32/cmd.exe', 'javascript:alert(1)', 'ms-settings:privacy', 'http://github.com/', 'https://github.com.evil/', 'https://github.com@evil/', 'https://user@github.com/', 'https://github.com:444/']) assert.equal(externalUrl(bad), null, bad)
})

test('video byte ranges and HEAD work; missing assets/API never return SPA HTML', async t => {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), 'rtp-assets-'))
  t.after(() => fs.rm(root, { recursive: true, force: true }))
  await fs.writeFile(path.join(root, 'index.html'), '<h1>Test page</h1>')
  await fs.writeFile(path.join(root, 'film.mp4'), '0123456789')
  const get = (url, init) => serveAsset(root, new Request('rtp://app' + url, init))
  const map = await get('/map')
  assert.equal(map.status, 200)
  assert.equal(await map.text(), '<h1>Test page</h1>')
  assert.match(map.headers.get('content-security-policy'), /script-src 'self'/)
  assert.doesNotMatch(map.headers.get('content-security-policy'), /unsafe-eval/)
  const film = await get('/film.mp4', { headers: { Range: 'bytes=2-5' } })
  assert.equal(film.status, 206)
  assert.equal(film.headers.get('content-range'), 'bytes 2-5/10')
  assert.equal(film.headers.get('content-type'), 'video/mp4')
  assert.equal(await film.text(), '2345')
  assert.equal(await (await get('/film.mp4', { headers: { Range: 'bytes=-3' } })).text(), '789')
  const head = await get('/film.mp4', { method: 'HEAD' })
  assert.equal(head.headers.get('content-length'), '10')
  assert.equal(await head.text(), '')
  for (const range of ['bytes=20-', 'bytes=8-3', 'bytes=0-1,3-4', 'bytes=-0', 'invalid']) assert.equal((await get('/film.mp4', { headers: { Range: range } })).status, 416)
  assert.equal((await get('/missing.js')).status, 404)
  assert.equal((await get('/film.mp4', { method: 'POST' })).status, 405)
  const api = await get('/api/device-readings')
  assert.equal(api.status, 503)
  assert.equal((await api.json()).configured, false)
})
